import models from '../models/index.js';

const { sequelize } = models;

async function cleanup() {
  try {
    await sequelize.authenticate();
    console.log('Database connected.');

    const [tables] = await sequelize.query('SHOW TABLES');
    const dbName = sequelize.config.database;
    const tableKey = `Tables_in_${dbName}`;

    for (const row of tables) {
      const tableName = row[tableKey] || Object.values(row)[0];
      const [indexes] = await sequelize.query(`SHOW INDEX FROM \`${tableName}\``);
      const keyNames = [...new Set(indexes.map((r) => r.Key_name))];

      // Identify duplicate index names generated by Sequelize alter sync (e.g. name_2, name_3, ...)
      const duplicateIndexes = keyNames.filter((name) => /_\d+$/.test(name));

      if (duplicateIndexes.length > 0) {
        console.log(`Table '${tableName}': dropping ${duplicateIndexes.length} duplicate index(es)...`);
        for (const indexName of duplicateIndexes) {
          try {
            await sequelize.query(`ALTER TABLE \`${tableName}\` DROP INDEX \`${indexName}\``);
            console.log(`  - Dropped index '${indexName}' from '${tableName}'`);
          } catch (err) {
            console.error(`  - Failed to drop index '${indexName}' from '${tableName}':`, err.message);
          }
        }
      } else {
        console.log(`Table '${tableName}': no duplicate indexes found (total: ${keyNames.length}).`);
      }
    }

    console.log('\nAll duplicate indexes have been cleaned up successfully!');
    process.exit(0);
  } catch (error) {
    console.error('Error during index cleanup:', error);
    process.exit(1);
  }
}

cleanup();
